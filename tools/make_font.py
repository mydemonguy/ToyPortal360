#!/usr/bin/env python3
"""Makes src/core/font8x16.inc: an 8x16 one-bit font for printable ASCII
(32-126), used by the on-screen character grid.

The glyphs are rasterised from DejaVu Sans Mono Bold (Bitstream Vera /
DejaVu font licence, which allows this) and thresholded to one bit.

    python3 tools/make_font.py [path/to/DejaVuSansMono-Bold.ttf] > src/core/font8x16.inc
    python3 tools/make_font.py --preview out.png   (an enlarged sample)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
W, H, SIZE, THRESHOLD = 8, 16, 13, 110


def glyphs(path):
    font = ImageFont.truetype(path, SIZE)
    ascent, _ = font.getmetrics()
    out = []
    for c in range(32, 127):
        im = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(im)
        # Centre the advance in the cell; baseline at row 12.
        adv = font.getlength(chr(c))
        d.text(((W - adv) / 2, 12 - ascent), chr(c), font=font, fill=255)
        rows = []
        for y in range(H):
            bits = 0
            for x in range(W):
                if im.getpixel((x, y)) >= THRESHOLD:
                    bits |= 0x80 >> x
            rows.append(bits)
        out.append(rows)
    return out


def main():
    args = sys.argv[1:]
    preview = None
    if args[:1] == ["--preview"]:
        preview = args[1]
        args = args[2:]
    g = glyphs(args[0] if args else FONT)
    if preview:
        text = ["Toy Portal 360 - Skylanders", "Spyro (Series 2) Legendary", "0123456789 !?.,:;()[]-+/'&",
                "abcdefghijklmnopqrstuvwxyz", "ABCDEFGHIJKLMNOPQRSTUVWXYZ"]
        im = Image.new("L", (W * 30, H * len(text)), 0)
        for row, line in enumerate(text):
            for col, ch in enumerate(line):
                rows = g[ord(ch) - 32]
                for y in range(H):
                    for x in range(W):
                        if rows[y] & (0x80 >> x):
                            im.putpixel((col * W + x, row * H + y), 255)
        im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(preview)
        return
    print("/* Generated by tools/make_font.py from DejaVu Sans Mono Bold. Do not edit. */")
    print("/* 95 glyphs (ASCII 32-126), 16 rows each, bit 7 = leftmost pixel. */")
    for i, rows in enumerate(g):
        ch = chr(i + 32)
        label = ch if ch not in "\\*/" else "0x%02X" % (i + 32)
        print("{%s}, /* %s */" % (", ".join("0x%02X" % r for r in rows), label))


main()
