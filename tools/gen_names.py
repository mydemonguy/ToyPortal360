#!/usr/bin/env python3
"""Generate figure name tables from RPCS3's Qt dialogs (GPL-2.0)."""
import re, sys
sky_src, dim_src, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
inf_src = sys.argv[4] if len(sys.argv) > 4 else None

def ascii(s):
    s = s.replace("’", "'").replace("‘", "'").replace("é", "e")
    s.encode("ascii")  # fail loudly on anything else
    return s.replace("\\", "\\\\").replace('"', '\\"')

def block(text, name):
    start = text.index(name)
    start = text.index("{", start)
    end = text.index("};", start)
    return text[start:end + 1]

sky = open(sky_src, encoding="utf-8").read()
rows = re.findall(r'\{\{(\d+),\s*0x([0-9A-Fa-f]+)\},\s*"((?:[^"\\]|\\.)*)"\}', block(sky, "list_skylanders"))
with open(f"{out_dir}/names_skylanders.inc", "w") as f:
    f.write("/* Generated by tools/gen_names.py from RPCS3 skylander_dialog.cpp. Do not edit. */\n")
    for i, v, n in rows:
        f.write(f'{{ {int(i)}, 0x{int(v,16):04X}, "{ascii(n)}" }},\n')
print("skylanders", len(rows))

dim = open(dim_src, encoding="utf-8").read()
for table, fname in (("list_minifigs", "names_dimensions.inc"), ("list_tokens", "names_dimensions_tokens.inc")):
    rows = re.findall(r'\{(\d+),\s*"((?:[^"\\]|\\.)*)"\}', block(dim, table))
    with open(f"{out_dir}/{fname}", "w") as f:
        f.write(f"/* Generated by tools/gen_names.py from RPCS3 dimensions_dialog.cpp ({table}). Do not edit. */\n")
        for i, n in rows:
            f.write(f'{{ {int(i)}, "{ascii(n)}" }},\n')
    print(table, len(rows))

if inf_src:
    inf = open(inf_src, encoding="utf-8").read()
    rows = re.findall(r'\{0x([0-9A-Fa-f]+),\s*\{(\d+),\s*"((?:[^"\\]|\\.)*)"\}\}', block(inf, "list_figures"))
    with open(f"{out_dir}/names_infinity.inc", "w") as f:
        f.write("/* Generated by tools/gen_names.py from RPCS3 infinity_dialog.cpp. Do not edit. */\n")
        for num, series, n in rows:
            f.write(f'{{ 0x{int(num,16):06X}, {int(series)}, "{ascii(n)}" }},\n')
    print("infinity", len(rows))
